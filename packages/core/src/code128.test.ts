import { describe, expect, it } from "vitest";
import { barcodeSvg, barPattern } from "./code128";

// Bars made by python-barcode (the shop computer's software) for the same codes.
const FROM_SHOP_SOFTWARE: [string, string][] = [
  ["100000", "11010011100110010001001101100110011011001100101100111001100011101011"],
  ["100203", "11010011100110010001001100110011010010011000111001011001100011101011"],
  ["IB21041", "1101001000011000100010100010110001011101111011011100100100100011001011110111010011100110111101010001100011101011"],
  ["IH6171", "110100100001100010001011000101000101110111101100100001010011010000111101101101100011101011"],
  ["IH615-LOT002", "11010010000110001000101100010100011001110100100111001101101110010010011011100100011011101000111011011011100010100111011001001110110011001110010101111001001100011101011"],
  ["ABH-ER-000001", "110100100001010001100010001011000110001010001001101110010001101000110001011101001101110010111011110110110011001101100110011001101100100010011001100011101011"],
  ["A", "1101001000010100011000100010110001100011101011"],
  ["7", "1101001000011101101110111010011001100011101011"],
  ["12345", "1101001110010110011100100010110001011110111011011100100111010110001100011101011"],
  ["X9", "110100100001110001011011100101100100100011001100011101011"],
  ["ab_c.d/1", "110100100001001011000010010000110101001100001000010110010011001110100001001101011100110010011100110100010001101100011101011"],
];

describe("code 128", () => {
  it.each(FROM_SHOP_SOFTWARE)("%s has the same bars as the shop software", (code, bits) => {
    expect(barPattern(code)).toBe(bits);
  });

  it("keeps codes that start with 99 followed by a letter", () => {
    // python-barcode drops the 99 here; the bars must still read back as 99A.
    const bits = barPattern("99A");
    expect(bits.startsWith("11010011100")).toBe(true); // start C
    expect(bits.length).toBe(11 * 5 + 13); // start, 99, to-B, A, checksum + stop
  });

  it("refuses characters that cannot be printed", () => {
    expect(() => barPattern("é")).toThrow();
    expect(() => barPattern("")).toThrow();
  });

  it("makes a scalable svg with quiet zones", () => {
    const svg = barcodeSvg("100000");
    expect(svg).toContain(`viewBox="0 0 ${barPattern("100000").length + 16} 1"`);
  });
});
